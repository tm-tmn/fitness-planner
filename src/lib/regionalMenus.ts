const parsed: Record<Region, Record<MealType, MenuItem[]>> = {} as never;
for (const region of Object.keys(DATA) as Region[]) {
  parsed[region] = {} as Record<MealType, MenuItem[]>;
  for (const meal of Object.keys(DATA[region]) as MealType[]) {
    parsed[region][meal] = DATA[region][meal].map((line) => {
      const [name, kcal, protein] = line.split("|");
      return { name, kcal: Number(kcal), protein: Number(protein) };
    });
  }
}

/** ประมาณภูมิภาคจากพิกัดแบบออฟไลน์ (ขอบเขตหยาบ ๆ ผู้ใช้เปลี่ยนเองได้) */
export function detectRegion(lat: number, lng: number): Region {
  const inThailand = lat >= 5.5 && lat <= 20.6 && lng >= 97.3 && lng <= 105.7;
  if (!inThailand) return "world";
  if (lat >= 13.45 && lat <= 14.2 && lng >= 100.2 && lng <= 100.95) return "bangkok";
  if (lat >= 16.8 && lng <= 101.2) return "north";
  if (lat >= 14.0 && lng >= 101.2) return "northeast";
  if (lat >= 16.8 && lng > 101.2) return "northeast";
  if (lat < 12.4 && lng <= 100.6) return "south";
  if (lat < 13.45 && lng >= 100.8 && lng <= 103.0) return "east";
  return "central";
}

/**
 * เลือกเมนูใกล้แคลอรี่ของมื้อเดิมที่สุด (ไม่ซ้ำชื่อเดิม) เลื่อนหน้าต่างด้วย offset เพื่อ "ดูตัวเลือกอื่น"
 */
export function suggestMenus(
  region: Region,
  meal: MealType,
  currentKcal: number | null,
  currentName: string,
  count = 4,
  offset = 0
): MenuItem[] {
  const pool = parsed[region][meal].filter((m) => m.name !== currentName);
  const target = currentKcal ?? (meal === "snack" ? 150 : 480);
  const sorted = [...pool].sort(
    (a, b) => Math.abs(a.kcal - target) - Math.abs(b.kcal - target)
  );
  if (sorted.length === 0) return [];
  const out: MenuItem[] = [];
  for (let i = 0; i < Math.min(count, sorted.length); i++) {
    out.push(sorted[(i + offset * count) % sorted.length]);
  }
  return out;
}

export function menuCount(): number {
  return Object.values(parsed).reduce(
    (n, byMeal) => n + Object.values(byMeal).reduce((m, l) => m + l.length, 0),
    0
  );
}
